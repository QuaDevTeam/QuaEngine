async function switchProject(path, name) {
  await app.evaluate(({ dialog, Menu }, path) => {
    dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [path] })
    Menu.getApplicationMenu().getMenuItemById('open-project').click()
  }, path)
  await page.locator(`#files[data-project-name="${name}"]`).waitFor({ state: 'attached', timeout: 30000 })
}
