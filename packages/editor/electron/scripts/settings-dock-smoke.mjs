import assert from 'node:assert/strict'
import { mkdir, mkdtemp, rm } from 'node:fs/promises'
import { createRequire } from 'node:module'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { _electron } from 'playwright'

const root = fileURLToPath(new URL('../../../../', import.meta.url))
const editorRoot = resolve(root, 'packages/editor/electron')
const require = createRequire(join(editorRoot, 'package.json'))
const temporary = await mkdtemp(join(tmpdir(), 'qua-settings-dock-'))
const artifacts = join(root, '.codex-tmp/editor-settings-dock')
await mkdir(artifacts, { recursive: true })
const env = { ...process.env, SHELL: '/bin/sh' }
delete env.ELECTRON_RUN_AS_NODE
const app = await _electron.launch({ executablePath: require('electron'), args: [editorRoot, `--user-data-dir=${join(temporary, 'profile')}`], env })
const page = await app.firstWindow()
page.setDefaultTimeout(12000)
const errors = []
page.on('pageerror', error => errors.push(error.message))
const capture = name => page.screenshot({ path: join(artifacts, `${name}.png`) })
try {
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1280, 850))
  await page.waitForFunction(() => window.innerWidth === 1280 && window.innerHeight === 850)
  await page.locator('#editor-empty h3').waitFor()
  const viewsButton = page.locator('.titlebar').getByRole('button', { name: '打开视图', exact: true })
  const assertViewsButton = async () => {
    const box = await viewsButton.boundingBox()
    const icon = await viewsButton.locator('svg').boundingBox()
    assert.equal(box.width, 26)
    assert.equal(box.height, 26)
    assert.ok(Math.abs(icon.x + icon.width / 2 - box.x - box.width / 2) < 1)
    assert.ok(Math.abs(icon.y + icon.height / 2 - box.y - box.height / 2) < 1)
    assert.equal(await viewsButton.getAttribute('title'), '打开视图或重置布局')
  }
  await assertViewsButton()
  await viewsButton.focus()
  await page.keyboard.press('Enter')
  await page.locator('.dock-dialog').waitFor()
  const picker = page.locator('qua-view-picker')
  const search = picker.getByRole('textbox', { name: '搜索视图', exact: true })
  await search.waitFor()
  assert.equal(await search.evaluate(input => input === document.activeElement), true)
  assert.equal(await picker.locator('.view-picker-group').count(), 4)
  assert.equal(await picker.getByRole('button', { name: '代码编辑器', exact: true }).getAttribute('data-state'), 'visible')
  assert.equal(await picker.getByRole('button', { name: '终端', exact: true }).getAttribute('data-state'), 'open')
  const inspector = picker.getByRole('button', { name: 'Inspector', exact: true })
  assert.ok(await inspector.isDisabled())
  assert.match(await inspector.textContent(), /需运行预览/u)
  for (const theme of ['dark', 'light']) {
    await page.emulateMedia({ colorScheme: theme })
    await page.waitForFunction(theme => document.documentElement.dataset.theme === theme, theme)
    await capture(`views-${theme}`)
  }
  await page.emulateMedia({ colorScheme: 'dark' })
  await search.fill('没有这个视图')
  await picker.getByRole('heading', { name: '没有匹配的视图' }).waitFor()
  assert.equal(await picker.locator('.view-picker-item').count(), 0)
  await capture('views-empty')
  await picker.getByRole('button', { name: '清空搜索' }).click()
  assert.equal(await search.inputValue(), '')
  assert.equal(await search.evaluate(input => input === document.activeElement), true)
  await search.fill('inspector')
  assert.equal(await picker.locator('.view-picker-item').count(), 1)
  await page.keyboard.press('Enter')
  assert.ok(await page.locator('.dock-dialog').isVisible())
  await search.fill('开发工具')
  assert.equal(await picker.locator('.view-picker-item').count(), 3)
  await page.keyboard.press('ArrowDown')
  assert.equal(await picker.getByRole('button', { name: '问题', exact: true }).evaluate(button => button === document.activeElement), true)
  await page.keyboard.press('End')
  assert.equal(await picker.getByRole('button', { name: '终端', exact: true }).evaluate(button => button === document.activeElement), true)
  await page.keyboard.press('Home')
  await page.keyboard.press('Enter')
  await page.locator('.dock-dialog').waitFor({ state: 'hidden' })
  assert.ok(await page.locator('#panel-problems').isVisible())
  await viewsButton.click()
  assert.equal(await search.inputValue(), '')
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(800, 650))
  await page.waitForFunction(() => window.innerWidth === 800 && window.innerHeight === 650)
  await capture('views-compact')
  assert.equal(await page.locator('.dock-dialog').evaluate(el => el.scrollWidth > el.clientWidth || el.scrollHeight > el.clientHeight), false)
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1280, 850))
  await page.waitForFunction(() => window.innerWidth === 1280 && window.innerHeight === 850)
  await page.keyboard.press('Escape')
  await page.locator('.dock-dialog').waitFor({ state: 'hidden' })
  assert.equal(await viewsButton.evaluate(button => button === document.activeElement), true)
  const fixedViews = ['explorer', 'search', 'git', 'story']
  const assertSidebar = async (active) => {
    assert.ok(await page.locator('.sidebar').isVisible())
    assert.equal(await page.locator('.sidebar .dock-header, .sidebar [role="tablist"], .sidebar [data-dock-view]').count(), 0)
    assert.equal(await page.locator('.sidebar > .sidebar-view:visible').count(), 1)
    for (const id of fixedViews) {
      assert.equal(await page.locator(`#activity-${id}`).getAttribute('draggable'), null)
      assert.equal(await page.locator(`[data-dock-view="${id}"]`).count(), 0)
      assert.equal(await page.locator(`#view-${id}`).isVisible(), id === active)
      assert.equal(await page.locator(`#activity-${id}`).getAttribute('aria-selected'), String(id === active))
    }
    assert.ok(await page.locator(`.sidebar #view-${active}`).count())
  }
  await assertSidebar('explorer')
  const initialLayout = await page.evaluate(() => localStorage.getItem('qua.editor.dock-layout.v1'))
  for (const id of fixedViews) {
    await page.locator(`#activity-${id}`).click()
    await assertSidebar(id)
  }
  assert.equal(await page.evaluate(() => localStorage.getItem('qua.editor.dock-layout.v1')), initialLayout)
  await page.locator('#activity-explorer').focus()
  await page.keyboard.press('ArrowDown')
  await assertSidebar('search')
  await page.keyboard.press('Home')
  await assertSidebar('explorer')
  const sidebarBox = await page.locator('.sidebar').boundingBox()
  const splitterBox = await page.locator('#sidebar-splitter').boundingBox()
  await page.mouse.move(splitterBox.x + 2, splitterBox.y + 60)
  await page.mouse.down()
  await page.mouse.move(splitterBox.x + 42, splitterBox.y + 60, { steps: 5 })
  await page.mouse.up()
  assert.equal(Math.round((await page.locator('.sidebar').boundingBox()).width), Math.round(sidebarBox.width + 40))
  await page.locator('#sidebar-splitter').focus()
  await page.keyboard.press('ArrowLeft')
  assert.equal(Math.round((await page.locator('.sidebar').boundingBox()).width), Math.round(sidebarBox.width + 30))
  await page.locator('#sidebar-splitter').dblclick()
  assert.equal(Math.round((await page.locator('.sidebar').boundingBox()).width), 270)
  await page.locator('[data-dock-view="properties"]').dragTo(page.locator('.sidebar'), { sourcePosition: { x: 3, y: 14 }, targetPosition: { x: 100, y: 180 } })
  assert.equal(await page.evaluate(() => localStorage.getItem('qua.editor.dock-layout.v1')), initialLayout)
  assert.equal(await page.locator('.dock-drop-indicator').isVisible(), false)
  await page.locator('#workbench-views').click()
  assert.equal(await page.locator('.dock-dialog').getByRole('button', { name: '资源管理器', exact: true }).count(), 0)
  await page.keyboard.press('Escape')
  await capture('workspace')
  await page.locator('#settings-button').click()
  await page.locator('#settings-dialog input[aria-label="搜索设置"]').waitFor()
  await page.getByLabel('字体大小', { exact: true }).fill('16')
  await page.getByLabel('字体大小', { exact: true }).press('Tab')
  await page.waitForFunction(() => JSON.parse(localStorage.getItem('qua-editor-preferences-v1')).fontSize === 16)
  await page.getByLabel('字体大小', { exact: true }).fill('200')
  await page.getByLabel('字体大小', { exact: true }).press('Tab')
  assert.equal(await page.getByLabel('字体大小', { exact: true }).evaluate(input => input.checkValidity()), false)
  await page.getByRole('button', { name: '恢复字体大小的默认值', exact: true }).click()
  await page.waitForFunction(() => document.querySelector('#setting-fontSize').validity.valid)
  await page.getByLabel('字体大小', { exact: true }).fill('16')
  await page.getByLabel('字体大小', { exact: true }).press('Tab')
  await capture('settings-editor')
  await page.getByLabel('搜索设置', { exact: true }).fill('终端')
  assert.equal(await page.locator('.settings-row').count(), 4)
  await page.getByLabel('终端字体大小', { exact: true }).fill('18')
  await page.getByLabel('终端字体大小', { exact: true }).press('Tab')
  await capture('settings-search')
  await page.getByRole('button', { name: '快捷键', exact: true }).click()
  await capture('settings-shortcuts')
  await page.keyboard.press('Escape')
  await page.locator('#tab-terminal').click()
  await page.locator('.terminal-instance .xterm-helper-textarea').waitFor()
  await page.waitForFunction(() => getComputedStyle(document.querySelector('.terminal-instance .xterm-rows')).fontSize === '18px')
  const session = await page.locator('#terminal-sessions').inputValue()
  await page.locator('[data-dock-view="terminal"]').click({ button: 'right' })
  await page.getByRole('button', { name: '向右拆分', exact: true }).click()
  assert.ok(await page.locator('#panel-terminal').isVisible())
  assert.ok(await page.locator('#panel-assets').isVisible())
  assert.equal(await page.locator('#terminal-sessions').inputValue(), session)
  await capture('split-terminal')
  await page.locator('[data-dock-view="terminal"] .dock-tab-close').click()
  assert.equal(await page.locator('#panel-terminal').isVisible(), false)
  await page.locator('#workbench-views').click()
  assert.equal(await picker.getByRole('button', { name: '终端', exact: true }).getAttribute('data-state'), 'closed')
  await search.fill('terminal')
  await page.keyboard.press('Enter')
  assert.equal(await page.locator('#terminal-sessions').inputValue(), session)
  await page.locator('[data-dock-view="properties"]').dragTo(page.locator('.dock-group[data-active-view="preview"]'), { sourcePosition: { x: 3, y: 14 }, targetPosition: { x: 20, y: 120 } })
  await capture('drag-properties')
  assert.ok(await page.locator('#panel-properties').isVisible())
  await page.locator('#settings-button').click()
  await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(800, 650))
  await page.getByRole('button', { name: '代码编辑器', exact: true }).click()
  await capture('settings-compact')
  assert.equal(await page.locator('#settings-dialog').evaluate(el => el.scrollWidth > el.clientWidth), false)
  await page.keyboard.press('Escape')
  // A saved layout from before the fixed sidebar can contain navigation mixed
  // into arbitrary groups. Restoring it must preserve every movable view.
  const movedLayout = await page.evaluate(() => localStorage.getItem('qua.editor.dock-layout.v1'))
  await page.evaluate(() => {
    const key = 'qua.editor.dock-layout.v1'
    const state = JSON.parse(localStorage.getItem(key))
    state.root = { kind: 'split', id: 'old-sidebar', axis: 'horizontal', ratio: 0.21, first: { kind: 'group', id: 'navigation', views: ['explorer'], active: 'explorer' }, second: state.root }
    state.closed.push('search', 'git', 'story')
    localStorage.setItem(key, JSON.stringify(state))
  })
  await page.reload()
  await page.locator('#editor-empty h3').waitFor()
  await assertSidebar('explorer')
  assert.equal(await page.evaluate(() => localStorage.getItem('qua.editor.dock-layout.v1')), movedLayout)
  await assertViewsButton()
  await capture('sidebar-compact')
  await page.locator('#settings-button').click()
  assert.equal(await page.getByLabel('字体大小', { exact: true }).inputValue(), '16')
  await page.getByRole('button', { name: '恢复字体大小的默认值', exact: true }).click()
  assert.equal(await page.getByLabel('字体大小', { exact: true }).inputValue(), '13')
  assert.deepEqual(errors, [])
  process.stdout.write('Settings and docking passed: grouped view picker, search, states, keyboard/focus, themes, fixed sidebar, resize, rejected sidebar drops, old layout migration, preferences, retained terminal, split, close/reopen, drag, compact layout and persistence.\n')
}
catch (error) {
  await capture('failure').catch(() => {})
  console.error(errors)
  throw error
}
finally {
  await app.close()
  await rm(temporary, { recursive: true, force: true })
}
